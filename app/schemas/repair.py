"""REPAIR-AI-EMPLOYEE-WORKFLOW-008A — Repair API schemas.

These schemas serialise the Repair Operation and its decoupled Proposals /
Actions for both the Mini App (full detail) and the Telegram fast path (the
single most important next action). Internal ids are exposed for the Mini App;
Telegram copy is generated by the bot reusing these same objects so it never
duplicates business truth in chat copy.
"""
from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field


class RepairCreateIn(BaseModel):
    issue: str = Field(min_length=1, max_length=200)
    issue_description: Optional[str] = None
    merchant_id: Optional[int] = None
    property_id: Optional[int] = None
    unit_id: Optional[int] = None
    created_source: str = "manual"
    closure_criteria: Optional[str] = None
    assignee_user_id: Optional[int] = None
    reported_by: Optional[int] = None


class RepairProposalIn(BaseModel):
    """Submit the NEXT versioned quote for a repair."""
    amount: Decimal = Field(ge=0, le=Decimal("100000000"))
    vendor: Optional[str] = None
    source: Optional[str] = None
    description: Optional[str] = None
    submit_as_expense: bool = False  # create a linked Expense alongside


class RepairDecisionIn(BaseModel):
    """Owner decision on one proposal version."""
    decision: str = Field(description="approve | reject")
    proposal_id: Optional[int] = None  # exactly one of proposal_id or version
    version: Optional[int] = None
    reason: Optional[str] = None      # required for reject
    expense_id: Optional[int] = None  # optionally link a pre-created expense on approve


class RepairRecordResultIn(BaseModel):
    """Human confirms the repair work is actually done (Drives to VERIFYING)."""
    verification_result: Optional[str] = None
    evidence_ids: Optional[list[int]] = None
    source: Optional[str] = None


class RepairVerifyIn(BaseModel):
    """Explicit verification that closes the repair."""
    verification_result: Optional[str] = None
    closure_signal: str = "HUMAN_CONFIRMED"
    source: Optional[str] = None


class RepairActionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    action_kind: str
    title: str
    description: Optional[str] = None
    status: str
    assigned_user_id: Optional[int] = None
    due_at: Optional[datetime] = None
    next_check_at: Optional[datetime] = None
    dedupe_key: str
    source_event: Optional[str] = None
    resolved_at: Optional[datetime] = None
    resolved_by: Optional[int] = None
    created_at: datetime


class RepairProposalOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    repair_id: int
    version: int
    vendor: Optional[str] = None
    source: Optional[str] = None
    description: Optional[str] = None
    amount: Decimal
    submitted_by: Optional[int] = None
    submitted_at: Optional[datetime] = None
    status: str
    decision_by: Optional[int] = None
    decision_at: Optional[datetime] = None
    rejection_reason: Optional[str] = None
    expense_id: Optional[int] = None


class RepairOut(BaseModel):
    """Mini App full detail view (sections: Issue/Operation, Proposals,
    Expenses, Actions, Evidence, Verification)."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    merchant_id: Optional[int] = None
    property_id: Optional[int] = None
    unit_id: Optional[int] = None
    issue: str
    issue_description: Optional[str] = None
    created_source: str
    reported_by: Optional[int] = None
    assignee_user_id: Optional[int] = None
    status: str
    next_action: Optional[str] = None
    waiting_on: Optional[str] = None
    blocked_reason: Optional[str] = None
    next_check_at: Optional[datetime] = None
    closure_criteria: Optional[str] = None
    verified_by: Optional[int] = None
    verified_at: Optional[datetime] = None
    verification_result: Optional[str] = None
    closed_at: Optional[datetime] = None
    closure_reason: Optional[str] = None
    operational_task_id: Optional[int] = None
    created_at: datetime


class RepairDetailOut(RepairOut):
    proposals: list[RepairProposalOut] = []
    actions: list[RepairActionOut] = []
    evidence: Optional[dict] = None
    expense_ids: list[int] = []


class RepairListOut(BaseModel):
    items: list[RepairOut]
    total: int
