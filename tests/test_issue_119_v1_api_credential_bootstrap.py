def _bootstrap_human_credential(db, *, username, workspace, role, raw_key=None):
    """Mirror scripts/create_v1_api_key.py HUMAN path in-process.

    Returns (user, membership, credential, raw_key). The raw_key is
    returned ONLY so the test can exercise authentication; production
    code captures the raw_key on stdout and discards it.
    """
    from app.core.security import generate_api_key, hash_api_key
    raw = raw_key or generate_api_key()
    org = db.query(Organization).filter(Organization.name == workspace).one_or_none()
    if org is None:
        org = Organization(name=workspace)
        db.add(org)
        db.flush()
    user = db.query(User).filter(User.username == username).one_or_none()
    if user is None:
        user = User(
            telegram_user_id=None,
            username=username,
            display_name=username,
            default_language="en-US",
        )
        db.add(user)
        db.flush()
    membership = (
        db.query(Membership)
        .filter(Membership.org_id == org.id, Membership.user_id == user.id)
        .order_by(Membership.id.asc())
        .first()
    )
    if membership is None:
        membership = Membership(
            org_id=org.id,
            user_id=user.id,
            role=role.value,
            state=MembershipState.ACTIVE.value,
        )
        db.add(membership)
        db.flush()
    cred = ApiCredential(
        user_id=user.id,
        key_hash=hash_api_key(raw),
        is_active=True,
        principal_type=V1PrincipalType.HUMAN.value,
        purpose=None,
    )
    db.add(cred)
    db.commit()
    return user, membership, cred, raw


def _bootstrap_system_credential(db, *, raw_key=None):
    raw = raw_key or generate_api_key()
    user = (
        db.query(User).filter(User.username == SYSTEM_SENTINEL_USERNAME).one_or_none()
    )
    if user is None:
        user = User(
            telegram_user_id=None,
            username=SYSTEM_SENTINEL_USERNAME,
            display_name="V1 SYSTEM scheduler sentinel",
            default_language="en-US",
        )
        db.add(user)
        db.flush()
    cred = ApiCredential(
        user_id=user.id,
        key_hash=hash_api_key(raw),
        is_active=True,
        principal_type=V1PrincipalType.SYSTEM.value,
        purpose="internal:scheduler",
    )
    db.add(cred)
    db.commit()
    return user, cred, raw


def test_fresh_db_human_owner_credential_authenticates():
    """FRESH-DB HUMAN OWNER: bootstrap → store SHA-256 hash → Bearer auth."""
    with v1_engine_ctx():
        factory = get_session_factory()
        db = factory()
        try:
            user, mship, cred, raw = _bootstrap_human_credential(
                db,
                username=f"owner-{uuid.uuid4().hex[:8]}",
                workspace="Issue119 Workspace",
                role=Role.OWNER,
            )
            assert cred.is_active is True
            assert cred.principal_type == V1PrincipalType.HUMAN.value
            assert cred.purpose is None
            # Raw key never persisted; only SHA-256 hex on disk.
            assert raw != cred.key_hash
            assert cred.key_hash == hash_api_key(raw)
            assert len(raw) >= 43  # secrets.token_urlsafe(32) → 43 chars
            # Round-trip auth via FastAPI dep.
            principal = get_current_principal(
                authorization=f"Bearer {raw}",
                db=db,
            )
            assert isinstance(principal, Principal)
            assert principal.role == Role.OWNER
            assert principal.user_id == user.id
            assert principal.org_id == mship.org_id
        finally:
            db.close()


