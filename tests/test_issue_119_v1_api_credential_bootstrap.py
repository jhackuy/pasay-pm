# A) Fresh-DB credential bootstrap
#
# A brand-new database, two human credentials (OWNER + SECRETARY) + one
# SYSTEM credential, generated by the same helper path the production
# script uses. Asserts every invariant the task calls out: 256-bit URL-safe
# raw key, SHA-256 hash on disk, no raw key persisted.
