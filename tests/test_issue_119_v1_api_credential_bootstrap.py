def test_active_system_with_unknown_purpose_is_rejected():
    """An active SYSTEM credential with an unknown purpose must NOT
    authenticate as a SYSTEM principal — the dep layer is the last line
    of defence even if the bootstrap script is bypassed."""
    from fastapi import HTTPException
    with v1_engine_ctx():
        factory = get_session_factory()
        db = factory()
        try:
            user = (
                db.query(User)
                .filter(User.username == SYSTEM_SENTINEL_USERNAME)
                .one_or_none()
            )
            if user is None:
                user = User(
                    telegram_user_id=None,
                    username=SYSTEM_SENTINEL_USERNAME,
                    display_name="S",
                    default_language="en-US",
                )
                db.add(user)
                db.flush()
            raw = generate_api_key()
            db.add(ApiCredential(
                user_id=user.id,
                key_hash=hash_api_key(raw),
                is_active=True,
                principal_type=V1PrincipalType.SYSTEM.value,
                purpose="internal:not-allowed",
            ))
            db.commit()
            with pytest.raises(HTTPException) as exc:
                get_system_principal(authorization=f"Bearer {raw}", db=db)
            assert exc.value.status_code == 401
        finally:
            db.close()
