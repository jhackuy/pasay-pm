def test_rotation_old_human_key_rejected_new_accepted():
    with v1_engine_ctx():
        factory = get_session_factory()
        db = factory()
        try:
            username = f"rot-h-{uuid.uuid4().hex[:8]}"
            _, _, _, old_raw = _bootstrap_human_credential(
                db,
                username=username,
                workspace="Rot Workspace",
                role=Role.OWNER,
            )
            # Old key authenticates before rotation.
            principal = get_current_principal(
                authorization=f"Bearer {old_raw}", db=db,
            )
            assert principal.role == Role.OWNER

            # Rotate: deactivate old, create new.
            user = db.query(User).filter(User.username == username).one()
            actives = (
                db.query(ApiCredential)
                .filter(
                    ApiCredential.user_id == user.id,
                    ApiCredential.is_active.is_(True),
                )
                .order_by(ApiCredential.id.asc())
                .all()
            )
            assert len(actives) == 1
            new_raw = generate_api_key()
            db.add(ApiCredential(
                user_id=user.id,
                key_hash=hash_api_key(new_raw),
                is_active=True,
                principal_type=V1PrincipalType.HUMAN.value,
                purpose=None,
            ))
            db.flush()
            for old in actives:
                old.is_active = False
            db.commit()

            # Old key: 401 invalid credentials.
            from fastapi import HTTPException
            with pytest.raises(HTTPException) as exc:
                get_current_principal(authorization=f"Bearer {old_raw}", db=db)
            assert exc.value.status_code == 401

            # New key: 200, role=OWNER.
            principal2 = get_current_principal(
                authorization=f"Bearer {new_raw}", db=db,
            )
            assert principal2.role == Role.OWNER
            assert principal2.user_id == user.id

            # Active credentials for this user: exactly 1 (the new one).
            actives_after = (
                db.query(ApiCredential)
                .filter(
                    ApiCredential.user_id == user.id,
                    ApiCredential.is_active.is_(True),
                )
                .all()
            )
            assert len(actives_after) == 1
            assert actives_after[0].key_hash == hash_api_key(new_raw)
        finally:
            db.close()


