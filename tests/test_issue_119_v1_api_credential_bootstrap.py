# E) Generated keys are 256-bit URL-safe
#
# Hard requirement 3 from the task: 256-bit URL-safe raw key, SHA-256
# hash on disk, never written to the DB in plaintext.
# ============================================================================


def test_generated_keys_are_256_bit_url_safe():
    """token_urlsafe(32) gives a 256-bit (32-byte) random key encoded
    base64url without padding → 43 characters, drawn from [A-Za-z0-9_-].

    Multiple samples are checked to ensure we don't depend on a single
    lucky string; entropy is enforced by the underlying ``secrets``
    module.
    """
    import re
    import string
    allowed = set(string.ascii_letters + string.digits + "-_")
    for _ in range(16):
        raw = generate_api_key()
        assert len(raw) == 43, f"unexpected raw key length {len(raw)}"
        assert all(c in allowed for c in raw), (
            f"raw key contains non-URL-safe characters: {raw!r}"
        )
        # SHA-256 hex is always 64 chars.
        h = hash_api_key(raw)
        assert len(h) == 64
        assert re.fullmatch(r"[0-9a-f]{64}", h)


def test_raw_key_never_persisted_only_hash_on_disk():
    """Hard requirement: only SHA-256 hash must be on disk; raw key must
    not appear in any persisted column."""
    with v1_engine_ctx():
        factory = get_session_factory()
        db = factory()
        try:
            raw = generate_api_key()
            user, _, cred, _ = _bootstrap_human_credential(
                db,
                username=f"sec-{uuid.uuid4().hex[:8]}",
                workspace="Raw Key Workspace",
                role=Role.SECRETARY,
                raw_key=raw,
            )
            # Re-read the credential from a fresh session.
            db.close()
            db = factory()
            rows = db.query(ApiCredential).all()
            for row in rows:
                assert raw not in (row.key_hash or "")
                assert raw not in (row.purpose or "")
                assert raw not in str(row.id)
        finally:
            db.close()


